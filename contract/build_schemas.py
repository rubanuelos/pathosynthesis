"""Generate the contract's JSON Schemas from emotion_vocabulary.json and diagrams.json.

    python contract/build_schemas.py      # writes score / turn / dialogue schemas
    python contract/check_contract.py     # then verify

Edit the vocabulary or diagram geometry, never the generated schemas by hand.
"""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
VERSION = "0.3"
INTERVALS = ["unison", "min2", "maj2", "min3", "maj3", "p4", "tritone",
             "p5", "min6", "maj6", "min7", "maj7", "octave"]
PHASES = ["mirror", "dwell", "transform", "resurface"]
TRAJECTORIES = ["hold", "amplify", "dissolve", "release", "transmute"]
LENGTHS = ["brief", "medium", "long"]


def load(name):
    return json.loads((HERE / name).read_text())


def emotions():
    v = load("emotion_vocabulary.json")
    return sorted({t for d in v["diagrams"] for t in d["include"]})


def active_diagrams():
    g = load("diagrams.json")["diagrams"]
    return {k: d for k, d in sorted(g.items()) if d["active"]}


def phase_is(p):
    return {"type": "object", "required": ["phase"], "properties": {"phase": {"const": p}}}


def score_schema():
    act = active_diagrams()
    all_positions = sorted({p["name"] for d in act.values() for p in d["positions"]})
    movement = {
        "type": "object", "additionalProperties": False,
        "required": ["phase", "at", "span", "heartbeat", "chord", "transition"],
        "properties": {
            "phase": {"enum": PHASES},
            "at": {"enum": all_positions,
                   "description": "Where in the chosen diagram this movement sits. Must be a position of `diagram` (enforced below)."},
            "span": {"enum": ["short", "medium", "long"],
                     "description": "Relative length of this movement. The orchestrator turns `length` + spans into seconds."},
            "heartbeat": {"type": "object", "additionalProperties": False,
                          "required": ["tempo", "regularity", "weight"], "properties": {
                              "tempo": {"enum": ["very_slow", "slow", "resting", "elevated", "racing"]},
                              "regularity": {"enum": ["steady", "uneven", "erratic"]},
                              "weight": {"enum": ["faint", "present", "heavy"]}}},
            "chord": {"type": "object", "additionalProperties": False,
                      "required": ["register", "color", "density", "brightness"], "properties": {
                          "register": {"enum": ["low", "mid", "high"]},
                          "color": {"type": "array", "minItems": 1, "maxItems": 5, "uniqueItems": True,
                                    "items": {"enum": INTERVALS},
                                    "description": "Intervals above the root, ordered by prominence."},
                          "density": {"enum": ["sparse", "medium", "thick"]},
                          "brightness": {"enum": ["dark", "veiled", "clear", "bright"]}}},
            "transition": {"enum": ["cut", "glide", "slow_glide"]}}}
    # per-diagram restriction of movements[].at
    per_diagram = [{
        "if": {"properties": {"diagram": {"const": name}}},
        "then": {"properties": {"movements": {"items": {"properties": {
            "at": {"enum": [p["name"] for p in d["positions"]]}}}}}}}
        for name, d in act.items()]
    weighted = {"type": "object", "additionalProperties": False, "required": ["emotion", "weight"],
                "properties": {
                    "emotion": {"$ref": "#/$defs/emotion"},
                    "weight": {"type": "number", "minimum": 0, "maximum": 1},
                    "heard": {"type": "string", "maxLength": 60,
                              "description": "Optional. The visitor's own word this term translates. Logged; never sent to SuperCollider."}}}
    return {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$id": "https://pathosynthesis.local/contract/score.schema.json",
        "title": "Pathosynthesis Score",
        "description": f"Contract v{VERSION}. Interpretation (01) -> orchestrator (03). Semantic choices only. GENERATED by build_schemas.py; do not edit by hand.",
        "type": "object", "additionalProperties": False,
        "required": ["contract_version", "diagram", "mirror_emotion", "mixture", "tension",
                     "intention", "intention_source", "trajectory", "length", "movements"],
        "$defs": {"emotion": {"enum": emotions(),
                              "description": "Vocabulary from the Nicolae diagrams. Provenance: emotion_vocabulary.json."},
                  "weighted_emotion": weighted,
                  "movement": movement},
        "properties": {
            "contract_version": {"const": VERSION},
            "diagram": {"enum": list(act), "description": "Which diagram frames the piece. Only active diagrams (diagrams.json)."},
            "mirror_emotion": {"$ref": "#/$defs/emotion",
                               "description": "The first emotion to mirror (iso principle). Must also appear in `mixture`."},
            "mixture": {"type": "array", "minItems": 1, "maxItems": 6, "items": {"$ref": "#/$defs/weighted_emotion"}},
            "destination": {"type": "array", "minItems": 1, "maxItems": 6, "items": {"$ref": "#/$defs/weighted_emotion"}},
            "tension": {"type": "string", "maxLength": 200},
            "intention": {"type": "string", "maxLength": 500},
            "intention_source": {"enum": ["stated", "inferred"],
                                 "description": "stated = the visitor said it; inferred = read from their answers."},
            "negotiation": {"type": "string", "maxLength": 240},
            "trajectory": {"enum": TRAJECTORIES},
            "length": {"enum": LENGTHS, "description": "Duration of the piece after the questionnaire. Seconds set by the orchestrator."},
            "movements": {
                "type": "array", "minItems": 3, "maxItems": 5,
                "prefixItems": [{"allOf": [{"$ref": "#/$defs/movement"}, phase_is("mirror")]}],
                "items": {"$ref": "#/$defs/movement"},
                "allOf": [{"contains": phase_is("mirror"), "maxContains": 1},
                          {"contains": phase_is("dwell"), "minContains": 1, "maxContains": 1},
                          {"contains": phase_is("resurface"), "minContains": 1, "maxContains": 1}]},
            "title": {"type": "string", "maxLength": 80}},
        "allOf": per_diagram}


def turn_schema():
    return {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$id": "https://pathosynthesis.local/contract/turn.schema.json",
        "title": "Pathosynthesis Questionnaire Turn",
        "description": f"Contract v{VERSION}. Interpretation (01) -> orchestrator (03), after each answer. GENERATED by build_schemas.py.",
        "type": "object", "additionalProperties": False,
        "required": ["action", "planned_questions", "hypothesis"],
        "properties": {
            "action": {"enum": ["ask", "compose"]},
            "question": {"type": "string", "minLength": 1, "maxLength": 200,
                         "description": "Required when action=ask. Spoken aloud by the voice node."},
            "planned_questions": {"type": "integer", "minimum": 2, "maximum": 5,
                                  "description": "Current estimate of how many questions this visitor needs in total, counting the opening one."},
            "hypothesis": {
                "type": "object", "additionalProperties": False,
                "description": "The working guess the next question is aimed at. Logged; never spoken.",
                "required": ["confidence"],
                "properties": {
                    "diagram": {"enum": list(active_diagrams())},
                    "at": {"type": "string", "maxLength": 40},
                    "mirror_emotion": {"enum": emotions()},
                    "trajectory": {"enum": TRAJECTORIES},
                    "length": {"enum": LENGTHS},
                    "unknown": {"type": "string", "maxLength": 200,
                                "description": "What the next question is trying to find out."},
                    "confidence": {"enum": ["low", "medium", "high"]}}}},
        "allOf": [{"if": {"properties": {"action": {"const": "ask"}}}, "then": {"required": ["question"]}}]}


def dialogue_schema():
    return {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$id": "https://pathosynthesis.local/contract/dialogue.schema.json",
        "title": "Pathosynthesis Dialogue",
        "description": f"Contract v{VERSION}. The questionnaire so far: orchestrator (03) -> interpretation (01). GENERATED by build_schemas.py.",
        "type": "object", "additionalProperties": False,
        "required": ["contract_version", "session_id", "exchanges"],
        "properties": {
            "contract_version": {"const": VERSION},
            "session_id": {"type": "string", "maxLength": 64},
            "lang": {"type": "string", "maxLength": 16, "description": "BCP-47, detected from the first answer."},
            "exchanges": {
                "type": "array", "minItems": 1, "maxItems": 5,
                "items": {"type": "object", "additionalProperties": False,
                          "required": ["question", "answer", "status"],
                          "properties": {
                              "question": {"type": "string", "maxLength": 200},
                              "answer": {"type": "string", "maxLength": 2000},
                              "status": {"enum": ["ok", "silence", "timeout"]},
                              "speech_s": {"type": "number", "minimum": 0},
                              "turn": {"$ref": "turn.schema.json",
                                       "description": "The interpretation turn returned after this answer, once known."}}}}}}


if __name__ == "__main__":
    for name, fn in (("score", score_schema), ("turn", turn_schema), ("dialogue", dialogue_schema)):
        (HERE / f"{name}.schema.json").write_text(json.dumps(fn(), indent=2, ensure_ascii=False) + "\n")
        print("wrote", f"{name}.schema.json")
